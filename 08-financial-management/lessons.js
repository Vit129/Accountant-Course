function parseNumberAfterEquals(text) {
  const match = text.match(/=\s*([\d,]+(?:\.\d+)?)/);
  if (!match) return null;
  return parseFloat(match[1].replace(/,/g, ''));
}

// สำหรับคำตอบหลายบรรทัด (เช่น "DFL = 2" และ "DCL = 5" คนละบรรทัด) — ค้นหาค่าตามป้ายชื่อ (label) เฉพาะบรรทัดนั้น
function parseLabeledValue(text, label) {
  const re = new RegExp(label + '\\s*=\\s*([\\d,]+(?:\\.\\d+)?)', 'i');
  const match = text.match(re);
  if (!match) return null;
  return parseFloat(match[1].replace(/,/g, ''));
}

